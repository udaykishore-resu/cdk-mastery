import * as path from 'node:path';
import * as cdk from 'aws-cdk-lib';
import * as dynamodb from 'aws-cdk-lib/aws-dynamodb';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as eventsources from 'aws-cdk-lib/aws-lambda-event-sources';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as sqs from 'aws-cdk-lib/aws-sqs';
import { EnvironmentTier } from '@cdk-mastery/shared';
import { Construct } from 'constructs';

export interface TestableStackProps extends cdk.StackProps {
  readonly tier: EnvironmentTier;
  /**
   * Attach a dead-letter queue to the work queue. Defaults to true; turning it
   * off is a *decision*, so the stack records a warning annotation you can test.
   */
  readonly enableDlq?: boolean;
  /** Reserved concurrency for the worker; omitted = unreserved. */
  readonly reservedConcurrency?: number;
}

/**
 * A stack whose only purpose is to have enough surface to exercise every
 * assertion primitive in `aws-cdk-lib/assertions`:
 *
 *   - a bucket whose DeletionPolicy depends on the tier      → hasResource + DeletionPolicy
 *   - a table with a GSI (array-valued props)                 → arrayWith / arrayEquals
 *   - a Lambda from an asset (unstable hash)                  → Match.anyValue / snapshot stabilisation
 *   - an SQS queue + optional DLQ                              → resourceCountIs / negative tests
 *   - IAM policies generated by grants                         → Capture, findResources
 *   - CfnOutput + CfnMapping + CfnParameter                    → hasOutput / hasMapping / hasParameter
 *   - a warning annotation                                     → Annotations.fromStack
 */
export class TestableStack extends cdk.Stack {
  readonly bucket: s3.Bucket;
  readonly table: dynamodb.TableV2;
  readonly queue: sqs.Queue;
  readonly worker: lambda.Function;
  readonly tableNameOutput: cdk.CfnOutput;

  constructor(scope: Construct, id: string, props: TestableStackProps) {
    super(scope, id, props);
    const { tier } = props;
    const removalPolicy = tier.retainStatefulResources ? cdk.RemovalPolicy.RETAIN : cdk.RemovalPolicy.DESTROY;

    // A parameter that a deploy pipeline could override — tested with hasParameter.
    const alarmEmail = new cdk.CfnParameter(this, 'AlarmEmail', {
      type: 'String',
      default: 'platform-team@example.com',
      description: 'Recipient for operational alarms',
    });

    // A mapping keyed by region — tested with hasMapping / findMappings.
    const regionConfig = new cdk.CfnMapping(this, 'RegionConfig', {
      mapping: {
        'us-east-1': { logBucketPrefix: 'use1' },
        'us-west-2': { logBucketPrefix: 'usw2' },
        'eu-west-1': { logBucketPrefix: 'euw1' },
      },
      lazy: true, // only rendered when findInMap is actually used
    });

    this.bucket = new s3.Bucket(this, 'Uploads', {
      versioned: true,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      encryption: s3.BucketEncryption.S3_MANAGED,
      removalPolicy,
      autoDeleteObjects: removalPolicy === cdk.RemovalPolicy.DESTROY,
      serverAccessLogsPrefix: `${regionConfig.findInMap(cdk.Aws.REGION, 'logBucketPrefix')}/`,
    });

    this.table = new dynamodb.TableV2(this, 'Orders', {
      partitionKey: { name: 'pk', type: dynamodb.AttributeType.STRING },
      sortKey: { name: 'sk', type: dynamodb.AttributeType.STRING },
      billing: dynamodb.Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: tier.highlyAvailable },
      removalPolicy,
      globalSecondaryIndexes: [
        { indexName: 'ByCustomer', partitionKey: { name: 'customerId', type: dynamodb.AttributeType.STRING } },
      ],
    });

    const enableDlq = props.enableDlq ?? true;
    let deadLetterQueue: sqs.DeadLetterQueue | undefined;
    if (enableDlq) {
      deadLetterQueue = {
        queue: new sqs.Queue(this, 'DeadLetter', { enforceSSL: true, retentionPeriod: cdk.Duration.days(14) }),
        maxReceiveCount: 3,
      };
    } else {
      // A warning, not an error: dev tiers may legitimately skip it, but it must be visible.
      cdk.Annotations.of(this).addWarningV2(
        'cdk-mastery:no-dlq',
        'Work queue has no dead-letter queue; poison messages will be retried until they expire',
      );
    }
    this.queue = new sqs.Queue(this, 'Work', {
      enforceSSL: true,
      visibilityTimeout: cdk.Duration.seconds(90), // ≥ 6× the function timeout, per the SQS/Lambda guidance
      deadLetterQueue,
    });

    this.worker = new lambda.Function(this, 'Worker', {
      runtime: lambda.Runtime.NODEJS_22_X,
      handler: 'index.handler',
      code: lambda.Code.fromAsset(path.join(__dirname, 'handlers')),
      timeout: cdk.Duration.seconds(15),
      memorySize: 256,
      reservedConcurrentExecutions: props.reservedConcurrency,
      environment: { TABLE_NAME: this.table.tableName, ALARM_EMAIL: alarmEmail.valueAsString },
    });
    this.worker.addEventSource(new eventsources.SqsEventSource(this.queue, { batchSize: 10 }));
    this.table.grantReadWriteData(this.worker);
    this.bucket.grantRead(this.worker);

    this.tableNameOutput = new cdk.CfnOutput(this, 'TableName', {
      value: this.table.tableName,
      description: 'DynamoDB table consumed by the worker',
      exportName: `${this.stackName}-TableName`,
    });
    new cdk.CfnOutput(this, 'WorkerArn', { value: this.worker.functionArn });
  }
}
