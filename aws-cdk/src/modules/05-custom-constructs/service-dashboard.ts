import * as cdk from 'aws-cdk-lib';
import * as cloudwatch from 'aws-cdk-lib/aws-cloudwatch';
import { Construct } from 'constructs';

/**
 * ServiceDashboard — one CloudWatch dashboard per service, built from `IMetric[]`.
 *
 * Accepting `IMetric` (not `Metric`) is the contract: anything produced by a `metric*`
 * method, a `MathExpression`, or a `metricX()` on an imported resource can be plotted. The
 * construct owns layout (rows of `columns` graphs) and nothing about semantics; callers
 * keep their metric definitions next to the resources that emit them.
 */
export interface ServiceDashboardProps {
  /** Shown in the dashboard name and the header widget. */
  readonly serviceName: string;
  /** Metrics to graph, one widget each, in order. */
  readonly metrics: cloudwatch.IMetric[];
  /** Alarms to show in a status widget at the top. @default - none */
  readonly alarms?: cloudwatch.IAlarm[];
  /** Graph widgets per row (1..4). @default 3 */
  readonly columns?: number;
  /** Default time range of the dashboard. @default 3 hours */
  readonly defaultInterval?: cdk.Duration;
}

export class ServiceDashboard extends Construct {
  readonly dashboard: cloudwatch.Dashboard;
  private readonly columns: number;
  private readonly metrics: cloudwatch.IMetric[] = [];
  private readonly alarms: cloudwatch.IAlarm[] = [];
  private rendered = false;

  constructor(scope: Construct, id: string, props: ServiceDashboardProps) {
    super(scope, id);
    this.columns = props.columns ?? 3;
    if (this.columns < 1 || this.columns > 4) throw new Error(`ServiceDashboard "${this.node.path}": columns must be 1..4`);
    if (!/^[A-Za-z0-9_-]+$/.test(props.serviceName)) throw new Error(`ServiceDashboard "${this.node.path}": serviceName must match [A-Za-z0-9_-]+`);

    this.dashboard = new cloudwatch.Dashboard(this, 'Resource', {
      dashboardName: `${props.serviceName}-service`,
      defaultInterval: props.defaultInterval ?? cdk.Duration.hours(3),
      periodOverride: cloudwatch.PeriodOverride.INHERIT,
    });
    this.dashboard.addWidgets(new cloudwatch.TextWidget({ markdown: `# ${props.serviceName}\nGenerated by cdk-mastery ServiceDashboard`, width: 24, height: 2 }));

    this.addMetrics(...props.metrics);
    this.addAlarms(...(props.alarms ?? []));

    // Widgets are laid out once, at synthesis, so `addMetrics` after construction still works.
    // `addValidation` runs before synthesis and after all constructors — a safe "finalise" hook.
    this.node.addValidation({
      validate: () => {
        this.render();
        return this.metrics.length === 0 ? ['at least one metric is required'] : [];
      },
    });
  }

  addMetrics(...metrics: cloudwatch.IMetric[]): void {
    if (this.rendered) throw new Error(`ServiceDashboard "${this.node.path}": cannot add metrics after synthesis`);
    this.metrics.push(...metrics);
  }

  addAlarms(...alarms: cloudwatch.IAlarm[]): void {
    if (this.rendered) throw new Error(`ServiceDashboard "${this.node.path}": cannot add alarms after synthesis`);
    this.alarms.push(...alarms);
  }

  private render(): void {
    if (this.rendered) return;
    this.rendered = true;
    if (this.alarms.length > 0) {
      this.dashboard.addWidgets(new cloudwatch.AlarmStatusWidget({ title: 'Alarms', alarms: this.alarms, width: 24, height: 3 }));
    }
    const width = Math.floor(24 / this.columns);
    for (let i = 0; i < this.metrics.length; i += this.columns) {
      const row = this.metrics.slice(i, i + this.columns).map(
        (metric) => new cloudwatch.GraphWidget({ title: titleOf(metric), left: [metric], width, height: 6, liveData: true }),
      );
      this.dashboard.addWidgets(...row);
    }
  }
}

/** Best-effort title: Metric and MathExpression both expose a label or a name. */
function titleOf(metric: cloudwatch.IMetric): string {
  const m = metric as { label?: string; metricName?: string; expression?: string };
  return m.label ?? m.metricName ?? m.expression ?? 'metric';
}
